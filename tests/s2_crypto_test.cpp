#include "Crypto.hpp"

#include <array>
#include <cstdint>
#include <span>
#include <vector>

#include <gtest/gtest.h>

// Authoritative known-answer vectors: NIST SP800-38C (AES-128-CCM), NIST
// SP800-38B (AES-128-CMAC), and RFC 7748 §5.2 (X25519).

namespace
{
template <std::size_t N> auto span(const std::array<std::uint8_t, N>& arr) -> std::span<const std::uint8_t>
{
    return std::span<const std::uint8_t>(arr);
}
}  // namespace

TEST(S2Crypto, CcmMatchesNistSp800_38c)
{
    // NIST SP800-38C Example 1: 7-byte nonce, 8-byte AAD, 4-byte payload, 4-byte tag.
    const S2::Crypto::Key key{
        0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47, 0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f};
    const std::array<std::uint8_t, 7> nonce{0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16};
    const std::array<std::uint8_t, 8> aad{0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07};
    const std::array<std::uint8_t, 4> plaintext{0x20, 0x21, 0x22, 0x23};
    const std::array<std::uint8_t, 8> expected{0x71, 0x62, 0x01, 0x5b, 0x4d, 0xac, 0x25, 0x5d};

    const auto out = S2::Crypto::ccmEncrypt(key, span(nonce), span(aad), span(plaintext), 4);
    EXPECT_EQ(out, std::vector<std::uint8_t>(expected.begin(), expected.end()));

    const auto back = S2::Crypto::ccmDecrypt(key, span(nonce), span(aad), span(expected), 4);
    ASSERT_TRUE(back.has_value());
    EXPECT_EQ(*back, std::vector<std::uint8_t>(plaintext.begin(), plaintext.end()));
}

TEST(S2Crypto, CcmDecryptRejectsTamperedTag)
{
    const S2::Crypto::Key key{
        0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47, 0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f};
    const std::array<std::uint8_t, 7> nonce{0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16};
    const std::array<std::uint8_t, 8> aad{0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07};
    std::array<std::uint8_t, 8> frame{0x71, 0x62, 0x01, 0x5b, 0x4d, 0xac, 0x25, 0x5d};
    frame.back() ^= 0xFF;  // corrupt the tag
    EXPECT_FALSE(S2::Crypto::ccmDecrypt(key, span(nonce), span(aad), span(frame), 4).has_value());
}

TEST(S2Crypto, CmacMatchesNistSp800_38b)
{
    const S2::Crypto::Key key{
        0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6, 0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c};
    // Example 1: empty message.
    const S2::Crypto::Mac emptyExpected{
        0xbb, 0x1d, 0x69, 0x29, 0xe9, 0x59, 0x37, 0x28, 0x7f, 0xa3, 0x7d, 0x12, 0x9b, 0x75, 0x67, 0x46};
    EXPECT_EQ(S2::Crypto::cmac(key, std::span<const std::uint8_t>{}), emptyExpected);

    // Example 2: one 16-byte block.
    const std::array<std::uint8_t, 16> message{
        0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96, 0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a};
    const S2::Crypto::Mac blockExpected{
        0x07, 0x0a, 0x16, 0xb4, 0x6b, 0x4d, 0x41, 0x44, 0xf7, 0x9b, 0xdd, 0x9d, 0xd0, 0x4a, 0x28, 0x7c};
    EXPECT_EQ(S2::Crypto::cmac(key, span(message)), blockExpected);
}

TEST(S2Crypto, X25519MatchesRfc7748)
{
    const S2::Crypto::PrivateKey scalar{0xa5, 0x46, 0xe3, 0x6b, 0xf0, 0x52, 0x7c, 0x9d, 0x3b, 0x16, 0x15,
                                        0x4b, 0x82, 0x46, 0x5e, 0xdd, 0x62, 0x14, 0x4c, 0x0a, 0xc1, 0xfc,
                                        0x5a, 0x18, 0x50, 0x6a, 0x22, 0x44, 0xba, 0x44, 0x9a, 0xc4};
    const S2::Crypto::PublicKey uCoord{0xe6, 0xdb, 0x68, 0x67, 0x58, 0x30, 0x30, 0xdb, 0x35, 0x94, 0xc1,
                                       0xa4, 0x24, 0xb1, 0x5f, 0x7c, 0x72, 0x66, 0x24, 0xec, 0x26, 0xb3,
                                       0x35, 0x3b, 0x10, 0xa9, 0x03, 0xa6, 0xd0, 0xab, 0x1c, 0x4c};
    const S2::Crypto::SharedSecret expected{0xc3, 0xda, 0x55, 0x37, 0x9d, 0xe9, 0xc6, 0x90, 0x8e, 0x94, 0xea,
                                            0x4d, 0xf2, 0x8d, 0x08, 0x4f, 0x32, 0xec, 0xcf, 0x03, 0x49, 0x1c,
                                            0x71, 0xf7, 0x54, 0xb4, 0x07, 0x55, 0x77, 0xa2, 0x85, 0x52};
    const auto shared = S2::Crypto::ecdh(scalar, uCoord);
    ASSERT_TRUE(shared.has_value());
    EXPECT_EQ(*shared, expected);
}

TEST(S2Crypto, X25519KeypairAgreement)
{
    const auto alice = S2::Crypto::generateKeyPair();
    const auto bob   = S2::Crypto::generateKeyPair();
    const auto a     = S2::Crypto::ecdh(alice.privateKey, bob.publicKey);
    const auto b     = S2::Crypto::ecdh(bob.privateKey, alice.publicKey);
    ASSERT_TRUE(a.has_value());
    ASSERT_TRUE(b.has_value());
    EXPECT_EQ(*a, *b);
    EXPECT_NE(alice.publicKey, bob.publicKey);  // distinct keypairs
}
